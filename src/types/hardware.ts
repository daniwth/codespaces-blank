import type { RoomId } from './player';

/** Silicon lottery grade rolled on every GPU purchase. */
export type SiliconQuality = 'bronze' | 'silver' | 'gold' | 'god';

/** Visual family used by the SpriteManager to draw a mining device. */
export type GpuStyle = 'card' | 'asic' | 'photonic' | 'singularity';

export interface GpuPalette {
  shroud: string;
  shroudDark: string;
  accent: string;
  pcb: string;
}

export interface GpuModel {
  id: string;
  name: string;
  brand: string;
  tier: number;
  /** Purchase price in cash ($). */
  price: number;
  /** Stock hashrate in H/s. */
  hashrate: number;
  /** Stock board power in watts (also equals heat generated at 100% load). */
  power: number;
  /** Thermal capacity C in J/°C. Bigger = slower to heat up and cool down. */
  thermalMass: number;
  style: GpuStyle;
  fans: 1 | 2 | 3;
  palette: GpuPalette;
}

export interface PsuModel {
  id: string;
  name: string;
  tier: number;
  price: number;
  /** Max DC load in watts. */
  capacity: number;
  /** Wall efficiency (0-1). Wall draw = load / efficiency. */
  efficiency: number;
  color: string;
}

export type CoolerKind = 'air' | 'liquid' | 'immersion' | 'cryo';

export interface CoolerModel {
  id: string;
  name: string;
  tier: number;
  price: number;
  /** Heat transfer coefficient contributed to the rack, in W/°C. */
  cooling: number;
  /** Own power draw in watts. */
  power: number;
  kind: CoolerKind;
}

export type RackStyle = 'bench' | 'steel' | 'cabinet' | 'gold';

export interface RackModel {
  id: string;
  name: string;
  /** Cash price. VIP racks are bought with gems instead. */
  price: number;
  gemPrice: number;
  slots: 2 | 4 | 8;
  fanSlots: 1 | 2 | 4;
  style: RackStyle;
  vip: boolean;
  /** Gold Edition: built-in power, zero electricity bill and no room line usage. */
  selfPowered: boolean;
  /** Multiplier on heat generated by the GPUs mounted inside. */
  heatMul: number;
}

/** Hidden per-unit silicon characteristics revealed through overclocking. */
export interface SiliconProfile {
  /** Max stable core offset (MHz) at stock voltage. */
  coreHeadroom: number;
  /** Max stable memory offset (MHz). */
  memHeadroom: number;
  /** Extra core MHz gained per +10 mV over stock. */
  vScale: number;
}

export interface OverclockSettings {
  /** Core clock offset in MHz. */
  core: number;
  /** Memory clock offset in MHz. */
  mem: number;
  /** Core voltage in mV (stock 1000). */
  voltage: number;
}

export interface GpuInstance {
  uid: string;
  modelId: string;
  quality: SiliconQuality;
  silicon: SiliconProfile;
  /** Currently applied (and validated) overclock profile. */
  oc: OverclockSettings;
  /** Hashrate bonus granted by the applied overclock (0 - 0.4). */
  ocBonus: number;
  /** Die temperature in °C. */
  temp: number;
  /** Permanent efficiency loss from silicon degradation (0 - 0.6). */
  wear: number;
  /** Thermal paste condition (0 - 1). */
  paste: number;
  /** True while in thermal-protection shutdown. */
  shutdown: boolean;
  /** Accumulated seconds spent above the wear threshold. */
  overheatSeconds: number;
}

export interface PsuInstance {
  uid: string;
  modelId: string;
}

export interface CoolerInstance {
  uid: string;
  modelId: string;
}

export interface RackInstance {
  uid: string;
  modelId: string;
  /** Room the rack is placed in, or null when stored in inventory. */
  roomId: RoomId | null;
  /** Floor pad index inside the room. */
  pad: number | null;
  gpuSlots: (string | null)[];
  fanSlots: (string | null)[];
  psuUid: string | null;
  /** Epoch ms until which the rig is rebooting (BSOD / inspection). */
  rebootUntil: number;
}

export type RackStatus =
  | 'online'
  /** Powered, but every GPU is in thermal-protection shutdown. */
  | 'overheat'
  | 'empty'
  | 'no_psu'
  | 'overload'
  | 'rebooting'
  | 'blackout'
  | 'stored';

/** Per-tick derived metrics (not persisted). */
export interface GpuLive {
  hash: number;
  running: boolean;
  throttled: boolean;
  heat: number;
  load: number;
}

export interface RackLive {
  status: RackStatus;
  /** DC load in watts. */
  load: number;
  /** Wall draw in watts. */
  wall: number;
  capacity: number;
  hash: number;
  maxTemp: number;
  cooling: number;
}

export type ComponentKind = 'gpu' | 'psu' | 'cooler' | 'rack';
